// 단계별 상승치 → 레벨별 누적값. [0]은 0단계(보너스 없음).
function cumulative(steps: Stats[]): Stats[] {
  const levels: Stats[] = [{}];
  for (const step of steps) {
    const next: Stats = { ...levels[levels.length - 1] };
    for (const [k, v] of Object.entries(step) as [keyof Stats, number][]) next[k] = (next[k] ?? 0) + v;
    levels.push(next);
  }
  return levels;
}

const toStats = (role: Role, row: Row): Stats =>
  Object.fromEntries(ENHANCE_COLUMNS[role].map((k, i) => [k, row[i]]));

export const enhanceLevels = (role: Role, type: CardType) =>
  cumulative(ENHANCE_STEPS[type].map((row) => toStats(role, row)));

export function awakenLevels(role: Role, type: CardType): Stats[] | null {
  const steps = AWAKEN_STEPS[role][type];
  return steps ? cumulative(steps) : null;
}
